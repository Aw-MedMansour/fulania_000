import asyncio,secrets,json
from playwright.async_api import async_playwright
async def main():
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True)
  page=await browser.new_page(viewport={"width":1280,"height":1800})
  await page.goto('http://localhost:8080/auth',wait_until='networkidle')
  ident='qa_'+secrets.token_hex(5)
  password=secrets.token_urlsafe(22)+'A7'
  await page.get_by_role('tab',name='Créer un compte',exact=True).click()
  await page.locator('#auth-id').fill(ident)
  await page.locator('#auth-password').fill(password)
  await page.locator('#auth-password-confirm').fill(password)
  await page.get_by_role('button',name='Créer mon compte',exact=True).click()
  await page.wait_for_url('**/hub',timeout=30000)
  print('SIGNUP: authenticated redirect to /hub')
  assert await page.evaluate("async () => {const {supabase}=await import('/src/integrations/supabase/client.ts'); return Boolean((await supabase.auth.getUser()).data.user)}")
  await page.screenshot(path='/tmp/browser/auth-flow/signup-success.png')
  await page.evaluate("async () => {const {supabase}=await import('/src/integrations/supabase/client.ts'); await supabase.auth.signOut()}")
  await page.goto('http://localhost:8080/auth',wait_until='networkidle')
  await page.locator('#auth-id').fill(ident)
  await page.locator('#auth-password').fill(password)
  await page.get_by_role('button',name='Se connecter',exact=True).click()
  await page.wait_for_url('**/hub',timeout=30000)
  await page.reload(wait_until='networkidle')
  assert await page.evaluate("async () => {const {supabase}=await import('/src/integrations/supabase/client.ts'); return Boolean((await supabase.auth.getUser()).data.user)}")
  print('SIGNIN: authenticated session persists after reload')
  await page.evaluate("async () => {const {supabase}=await import('/src/integrations/supabase/client.ts'); await supabase.auth.signOut()}")
  await page.goto('http://localhost:8080/auth',wait_until='networkidle')
  await page.locator('#auth-id').fill(ident)
  await page.locator('#auth-password').fill(secrets.token_urlsafe(15))
  await page.get_by_role('button',name='Se connecter',exact=True).click()
  await page.get_by_role('alert').wait_for()
  print('WRONG PASSWORD: visible error, submit enabled:',await page.get_by_role('button',name='Se connecter',exact=True).is_enabled())
  await page.screenshot(path='/tmp/browser/auth-flow/login-error.png')
  await browser.close()
asyncio.run(main())
