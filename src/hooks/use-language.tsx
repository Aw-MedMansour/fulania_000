// Module-level current language used by route head() functions (called outside React tree).
// Always reflects the user's active language. SSR default is "fr".
let _currentLang: Lang = "fr";
export function getCurrentLang(): Lang {
  return _currentLang;
}
// Fallback chain: requested lang → FR → EN → key itself.
// Logs a warning (once per lang+key) when a translation is missing or empty
// so we surface incoherent UI without spamming the console.
const FALLBACK_CHAIN: Lang[] = ["fr", "en"];
const _missingLogged = new Set<string>();
function resolveTranslation(lang: Lang, key: string): string {
  const primary = translations[lang]?.[key];
  if (primary && primary.trim() !== "") return primary;

  for (const fb of FALLBACK_CHAIN) {
    if (fb === lang) continue;
    const v = translations[fb]?.[key];
    if (v && v.trim() !== "") {
      const sig = `${lang}::${key}`;
      if (!_missingLogged.has(sig)) {
        _missingLogged.add(sig);
        console.warn(`[i18n] Missing translation for "${key}" in "${lang}" — falling back to "${fb}".`);
      }
      return v;
    }
  }

  const sig = `!!${key}`;
  if (!_missingLogged.has(sig)) {
    _missingLogged.add(sig);
    console.error(`[i18n] No translation found for "${key}" in any language. Returning key.`);
  }
  return key;
}

export function tFor(lang: Lang, key: string): string {
  return resolveTranslation(lang, key);
}

// BCP-47 locale for Web Speech / Intl APIs. Pulaar has no TTS voice everywhere,
// fall back to French (closest phonology for the Fuuta region).
export function bcp47(lang: Lang): string {
  switch (lang) {
    case "fr": return "fr-FR";
    case "en": return "en-US";
    case "ar": return "ar-SA";
    case "ff": return "fr-FR";
  }
}

// Read persisted language synchronously so the very first client render uses
// the user's chosen language — eliminates the brief flash of French (FOUC)
// on every navigation. SSR still emits "fr" markup; React 18 reconciles the
// mismatch on hydration and we suppress hydration warnings via
// suppressHydrationWarning on translated text containers where needed.
function readStoredLang(): Lang {
  if (typeof window === "undefined") return "fr";
  try {
    const stored = window.localStorage.getItem("fulania.lang") as Lang | null;
    if (stored && translations[stored]) return stored;
  } catch {}
  return "fr";
}
