type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  dialect: Dialect;
  setDialect: (d: Dialect) => void;
  t: (key: string) => string;
};
const LangCtx = createContext<Ctx | null>(null);

// Module-level current language used by route head() functions (called outside React tree).
// Always reflects the user's active language. SSR default is "fr".
let _currentLang: Lang = "fr";
export function getCurrentLang(): Lang {
  return _currentLang;
}
// Fallback chain: requested lang → FR → EN → key itself.
// Logs a warning (once per lang+key) when a translation is missing or empty
// so we surface incoherent UI without spamming the console.
const FALLBACK_CHAIN: Lang[] = ["fr", "en"];
const _missingLogged = new Set<string>();
function resolveTranslation(lang: Lang, key: string): string {
  const primary = translations[lang]?.[key];
  if (primary && primary.trim() !== "") return primary;

  for (const fb of FALLBACK_CHAIN) {
    if (fb === lang) continue;
    const v = translations[fb]?.[key];
    if (v && v.trim() !== "") {
      const sig = `${lang}::${key}`;
      if (!_missingLogged.has(sig)) {
        _missingLogged.add(sig);
        console.warn(`[i18n] Missing translation for "${key}" in "${lang}" — falling back to "${fb}".`);
      }
      return v;
    }
  }

  const sig = `!!${key}`;
  if (!_missingLogged.has(sig)) {
    _missingLogged.add(sig);
    console.error(`[i18n] No translation found for "${key}" in any language. Returning key.`);
  }
  return key;
}

export function tFor(lang: Lang, key: string): string {
  return resolveTranslation(lang, key);
}

// BCP-47 locale for Web Speech / Intl APIs. Pulaar has no TTS voice everywhere,
// fall back to French (closest phonology for the Fuuta region).
export function bcp47(lang: Lang): string {
  switch (lang) {
    case "fr": return "fr-FR";
    case "en": return "en-US";
    case "ar": return "ar-SA";
    case "ff": return "fr-FR";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");
  const [dialect, setDialectState] = useState<Dialect>("fouta_toro");
  const router = useRouter();

  useEffect(() => {
    try {
      const stored = localStorage.getItem("fulania.lang") as Lang | null;
      if (stored && translations[stored]) {
        setLangState(stored);
        _currentLang = stored;
      }
      const storedD = localStorage.getItem("fulania.dialect") as Dialect | null;
      if (storedD && DIALECTS.some((d) => d.code === storedD)) setDialectState(storedD);
    } catch {}
  }, []);

  useEffect(() => {
    _currentLang = lang;
    const entry = LANGUAGES.find((l) => l.code === lang);
    if (typeof document !== "undefined" && entry) {
      document.documentElement.lang = lang;
      document.documentElement.dir = entry.dir;
    }
    // Re-run route head() so meta title/description follow the language change.
    router.invalidate();
  }, [lang, router]);

  const setLang = (l: Lang) => {
    _currentLang = l;
    setLangState(l);
    try { localStorage.setItem("fulania.lang", l); } catch {}
  };
  const setDialect = (d: Dialect) => {
    setDialectState(d);
    try { localStorage.setItem("fulania.dialect", d); } catch {}
  };



  const t = (key: string) => resolveTranslation(lang, key);

  return <LangCtx.Provider value={{ lang, setLang, dialect, setDialect, t }}>{children}</LangCtx.Provider>;
}

export function useLanguage(): Ctx {
  const ctx = useContext(LangCtx);
  if (!ctx) return { lang: "fr", setLang: () => {}, dialect: "fouta_toro", setDialect: () => {}, t: (k) => resolveTranslation("fr", k) };
  return ctx;
}
